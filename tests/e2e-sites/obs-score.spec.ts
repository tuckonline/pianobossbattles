import {test,expect} from "@playwright/test";
import {installMidiKeyboard,playNotes,sendMidi} from "./helpers/midi";
import {practiceLibrary} from "../../hosted/practice-library";
import {noteGroups} from "../../hosted/sight-library";

test("score-only source follows selection and MIDI independently of practice scrolling",async({browser})=>{
  test.setTimeout(120000);
  const id=`obs-score-${Date.now()}`;
  const extraHTTPHeaders={"oai-authenticated-user-id":id,"oai-authenticated-user-email":`${id}@example.test`};
  const pc=await browser.newContext({extraHTTPHeaders,viewport:{width:1440,height:900}});
  const oc=await browser.newContext({extraHTTPHeaders,viewport:{width:1920,height:700}});
  await oc.route("**/assets/**",route=>route.continue());
  await pc.route("**/assets/**",route=>route.continue());
  const p=await pc.newPage(),o=await oc.newPage();
  try {
    await installMidiKeyboard(p);
    await p.goto("http://127.0.0.1:8787/student/practice?collection=hanon");
    await o.goto("http://127.0.0.1:8787/obs/score");
    await expect(o.locator(".notation .note").first()).toBeVisible();
    await expect(o.locator("nav,button,input,select,.game-hud,.obs-panel,.practice-keyboard-panel")).toHaveCount(0);
    await expect(o.getByRole("main",{name:"OBS score only: Hanon No. 1"})).toBeVisible();
    await expect(o.locator(".sight-score")).not.toContainText("Hanon No. 1");
    await expect(p.locator(".sight-score")).not.toContainText("Hanon No. 1");
    const banner=await oc.newPage();
    await banner.goto("http://127.0.0.1:8787/obs");
    await expect(banner.locator(".obs-piece h1")).toHaveText("Hanon No. 1");
    await banner.close();
    const before=await o.evaluate(()=>scrollY);
    await p.evaluate(()=>window.scrollTo(0,document.body.scrollHeight));
    await expect.poll(()=>o.evaluate(()=>scrollY)).toBe(before);
    await p.getByRole("button",{name:"Connect keyboard",exact:true}).click();
    await p.getByRole("button",{name:"Start MIDI practice",exact:true}).click();
    await expect(p.getByRole("button",{name:"Pause practice",exact:true})).toBeVisible();
    const notes=noteGroups(practiceLibrary[0],"both").flatMap(g=>g.pitches);
    await playNotes(p,notes.slice(0,12));
    await expect(o.locator(".practice-note-correct")).toHaveCount(12);
    const svg=await o.locator(".notation svg").first().elementHandle();
    await sendMidi(p,[[0x90,61,90],[0x80,61,0]]);
    await playNotes(p,notes.slice(12,18*16));
    // Wait for the final MIDI snapshot before testing scroll independence.
    await expect(o.locator(".practice-note-correct")).toHaveCount(18*16);
    await expect.poll(()=>o.locator('.notation').getAttribute('data-broadcast-first')).not.toBe('0');
    await expect(o.locator(".sight-active-measure")).toHaveCount(1);
    await expect.poll(()=>o.locator(".sight-active-measure").evaluate(e=>e.getBoundingClientRect().bottom)).toBeLessThan(700);
    expect(await svg!.evaluate(e=>e===document.querySelector(".notation svg"))).toBe(true);
    const at=await o.evaluate(()=>scrollY);
    await p.evaluate(()=>window.scrollTo(0,0));
    await expect.poll(()=>o.evaluate(()=>scrollY)).toBe(at);
    await o.screenshot({path:"../../work/obs-score-hanon.png"});
    await o.reload();
    await expect(o.locator(".practice-note-correct")).toHaveCount(18*16);
    await expect.poll(()=>o.locator('.notation').getAttribute('data-broadcast-first')).not.toBe('0');
    await p.getByRole("button",{name:"Stop practice",exact:true}).click();
    // Remote MusicXML and a custom passage both use the same authenticated catalog.
    await p.goto("http://127.0.0.1:8787/student/practice?collection=bach&exercise=10001");
    await expect(o.getByRole("main",{name:/OBS score only: .*Minuet in G major/})).toBeVisible();
    await expect(o.locator(".notation .note").first()).toBeVisible();
    await expect(o.locator(".sight-score")).not.toContainText("Minuet in G major");
    await o.screenshot({path:"../../work/obs-score-bach.png"});
    await p.goto("http://127.0.0.1:8787/student/practice?collection=moonlight");
    await p.getByLabel("Start measure",{exact:true}).fill("17");
    await p.getByLabel("End measure",{exact:true}).fill("25");
    await p.getByRole("button",{name:"Use measures",exact:true}).click();
    await expect(o.getByRole("main",{name:"OBS score only: Moonlight Sonata · measures 17–25"})).toBeVisible();
    await expect(o.locator(".notation .measure")).toHaveCount(9);
    await oc.setOffline(true);
    await p.getByLabel("Start measure",{exact:true}).fill("3");
    await p.getByLabel("End measure",{exact:true}).fill("3");
    await p.getByRole("button",{name:"Use measures",exact:true}).click();
    await oc.setOffline(false);
    await expect(o.getByRole("main",{name:"OBS score only: Moonlight Sonata · measure 3"})).toBeVisible();
    await expect(o.locator(".notation .measure")).toHaveCount(1);
    await expect(o.locator("button,nav,input,select")).toHaveCount(0);
    await expect(o.locator(".sight-score")).not.toContainText("Moonlight Sonata");
    await expect(o.locator(".schmitt-score-title")).toHaveCount(0);
    await o.screenshot({path:"../../work/obs-score-single.png"});
    await p.goto("http://127.0.0.1:8787/student/sight-read");
    await expect(o.getByRole("main",{name:"OBS score only: Hannah Smith Part 1 · Exercise 1"})).toBeVisible();
    await p.getByLabel("Hands",{exact:true}).selectOption("left");
    await p.getByRole("button",{name:"Connect keyboard",exact:true}).click();
    await p.getByRole("button",{name:"Start MIDI practice",exact:true}).click();
    const {sightLibrary}=await import("../../hosted/sight-library");
    await playNotes(p,noteGroups(sightLibrary[0],"left").slice(0,4).flatMap(g=>g.pitches));
    await expect(o.locator('.practice-note-correct[data-hand="left"]')).toHaveCount(4);
    await expect(o.locator('.practice-note-correct[data-hand="right"]')).toHaveCount(0);
    await o.setViewportSize({width:1280,height:440});
    await expect.poll(()=>o.locator(".sight-active-measure").evaluate(e=>e.getBoundingClientRect().bottom)).toBeLessThan(440);
    await expect(o.locator("nav,button,input,select")).toHaveCount(0);
  } finally {await pc.close();await oc.close();}
});

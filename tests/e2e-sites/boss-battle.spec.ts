async function ink(page:Page){return page.locator('.notation .system').evaluateAll(nodes=>{
  const boxes=nodes.filter(n=>getComputedStyle(n).visibility==='visible').map(n=>n.getBoundingClientRect());
  return {left:Math.min(...boxes.map(b=>b.left)),right:Math.max(...boxes.map(b=>b.right)),top:Math.min(...boxes.map(b=>b.top)),bottom:Math.max(...boxes.map(b=>b.bottom))};
});}

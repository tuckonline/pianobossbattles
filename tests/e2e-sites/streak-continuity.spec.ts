import {test,expect} from '@playwright/test';
import {sightLibrary,noteGroups} from '../../hosted/sight-library';
import {installMidiKeyboard,playNotes,sendMidi} from './helpers/midi';

test('MIDI streak survives loop and exercise boundaries, reload and preview; only wrong notes break it',async({page})=>{
  test.setTimeout(90000);
  const id=`carry-${crypto.randomUUID()}`;
  await page.context().setExtraHTTPHeaders({'oai-authenticated-user-id':id,'oai-authenticated-user-email':`${id}@example.test`});
  await page.context().route('**/assets/**',r=>r.continue());
  await installMidiKeyboard(page);
  await page.goto('/student/sight-read');
  const panel=page.getByRole('region',{name:'Pianist progression'});
  const combo=panel.locator('.game-combo strong');
  await expect(panel.getByText('Connecting progression…')).toHaveCount(0);
  await page.getByRole('button',{name:'Connect keyboard',exact:true}).click();
  await page.getByLabel('Practice loops',{exact:true}).fill('2');
  await page.getByRole('button',{name:'Start MIDI practice',exact:true}).click();
  const notes=noteGroups(sightLibrary[0],'both').flatMap(g=>g.pitches);
  await playNotes(page,notes);
  await expect(page.getByText('Loop 2 of 2',{exact:true})).toBeVisible();
  await expect(combo).toHaveText(String(notes.length));
  await playNotes(page,notes);
  await expect(page.getByText(/2 loops complete · Saved · 100%/)).toBeVisible();
  await expect(combo).toHaveText(String(notes.length*2));
  await page.getByLabel('Exercise',{exact:true}).selectOption('2');
  await expect(combo).toHaveText(String(notes.length*2));
  await page.getByRole('button',{name:'Start MIDI practice',exact:true}).click();
  const next=noteGroups(sightLibrary[1],'both').flatMap(g=>g.pitches);
  await playNotes(page,next.slice(0,4));
  const total=notes.length*2+4;
  await expect(combo).toHaveText(String(total));
  await page.getByRole('button',{name:'Stop practice',exact:true}).click();
  await expect(combo).toHaveText(String(total));
  await expect.poll(async()=>{const r=await page.request.post('/api/platform',{headers:{origin:new URL(page.url()).origin},data:{action:'gameState'}});return (await r.json()).streak;}).toBe(total);
  await page.reload();
  await expect(combo).toHaveText(String(total));
  await panel.getByText('Progression & recording controls',{exact:true}).click();
  await panel.getByRole('button',{name:'Preview +10 combo',exact:true}).click();
  await panel.getByRole('button',{name:'Exit preview',exact:true}).click();
  await expect(combo).toHaveText(String(total));
  await page.getByRole('button',{name:'Connect keyboard',exact:true}).click();
  await page.getByRole('button',{name:'Start MIDI practice',exact:true}).click();
  await sendMidi(page,[[0x80,60,0],[0xb0,64,127]]);
  await expect(combo).toHaveText(String(total));
  await playNotes(page,[1]);
  await expect(combo).toHaveText('0');
});
